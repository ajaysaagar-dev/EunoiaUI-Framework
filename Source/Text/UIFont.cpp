bool UIFont::Create(float size, bool isBold) {
    m_size = size;
    m_bold = isBold;
    m_scale = 1.0f;
    BuildEmbeddedFont(size, isBold);
    return true;
}

void UIFont::Destroy() {
    // Clear metrics
    for (int i = 0; i < 128; ++i) {
        m_glyphs[i] = UIGlyph();
    }
}

void UIFont::Rescale(float factor) {
    if (factor <= 0.0f) return;
    m_scale = factor;
    BuildEmbeddedFont(m_size * factor, m_bold);
}

void UIFont::BuildEmbeddedFont(float size, bool isBold) {
    if (!Sheet->Width || !Sheet->Height) {
        Sheet->Create(512, 512);
    }

    int startY = isBold ? 128 : 0;
    int cellW = 10;
    int cellH = 14;
    int cols = Sheet->Width / cellW;

    float charWidth = size * 0.55f;
    float charHeight = size;

    for (int c = 32; c <= 126; ++c) {
        int idx = c - 32;
        int col = (c - 32) % cols;
        int row = (c - 32) / cols;

        int px = col * cellW;
        int py = startY + row * cellH;

        // Rasterize 5x7 into sheet
        for (int x = 0; x < 5; ++x) {
            unsigned char colBits = s_font5x7[idx][x];
            for (int y = 0; y < 7; ++y) {
                if (colBits & (1 << y)) {
                    int dstX = px + x;
                    int dstY = py + y;
                    int pIndex = (dstY * Sheet->Width + dstX) * 4;
                    if (pIndex + 3 < (int)Sheet->Pixels.size()) {
                        Sheet->Pixels[pIndex + 0] = 255;
                        Sheet->Pixels[pIndex + 1] = 255;
                        Sheet->Pixels[pIndex + 2] = 255;
                        Sheet->Pixels[pIndex + 3] = 255;
                        if (isBold && dstX + 1 < Sheet->Width) {
                            int bIndex = (dstY * Sheet->Width + dstX + 1) * 4;
                            Sheet->Pixels[bIndex + 0] = 255;
                            Sheet->Pixels[bIndex + 1] = 255;
                            Sheet->Pixels[bIndex + 2] = 255;
                            Sheet->Pixels[bIndex + 3] = 255;
                        }
                    }
                }
            }
        }

        UIGlyph& g = m_glyphs[c];
        g.SourceUV = UIRectangle(
            (float)px / Sheet->Width,
            (float)py / Sheet->Height,
            5.0f / Sheet->Width,
            7.0f / Sheet->Height
        );
        g.Size = UIVector(charWidth, charHeight);
        g.Offset = UIVector(0.0f, 0.0f);
        g.Advance = (c == ' ') ? (charWidth * 0.75f) : charWidth;
    }

    // Set fallback glyph
    m_glyphs[0] = m_glyphs[' '];
    Sheet->Dirty = true;
}

UIVector UIFont::Measure(const char* text, int length) const {
    if (!text) return UIVector(0.0f, 0.0f);
    float width = 0.0f;
    float maxWidth = 0.0f;
    float height = LineHeight();

    int n = (length >= 0) ? length : (int)std::strlen(text);
    for (int i = 0; i < n; ++i) {
        char c = text[i];
        if (c == '\n') {
            maxWidth = std::max(maxWidth, width);
            width = 0.0f;
            height += LineHeight();
            continue;
        }
        unsigned char uc = (unsigned char)c;
        if (uc < 128) {
            width += m_glyphs[uc].Advance;
        } else {
            width += m_glyphs['?'].Advance;
        }
    }
    maxWidth = std::max(maxWidth, width);
    return UIVector(maxWidth, height);
}

